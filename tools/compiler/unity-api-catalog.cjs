class UnityApiCatalog {
  constructor() {
    this.entries = new Map(Object.entries(UNITY_API_ENTRIES));
  }

  /**
   * Lookup API by full ID or simple name (e.g. "Vector3.Lerp" or "UnityEngine.Vector3.Lerp")
   * @param {string} nameOrId
   * @returns {UnityApiMetadata | null}
   */
  lookup(nameOrId) {
    if (!nameOrId) return null;
    if (this.entries.has(nameOrId)) {
      return this.entries.get(nameOrId);
    }
    for (const entry of this.entries.values()) {
      if (entry.unityName === nameOrId || entry.id.endsWith(`.${nameOrId}`)) {
        return entry;
      }
    }
    return null;
  }

  /**
   * Retrieve all APIs belonging to a specific category
   * @param {string} category
   * @returns {UnityApiMetadata[]}
   */
  getByCategory(category) {
    const results = [];
    for (const entry of this.entries.values()) {
      if (entry.category === category) results.push(entry);
    }
    return results;
  }

  /**
   * Retrieve all APIs with GC risk
   * @returns {UnityApiMetadata[]}
   */
  getGcRisks() {
    const results = [];
    for (const entry of this.entries.values()) {
      if (entry.gcRisk) results.push(entry);
    }
    return results;
  }

  /**
   * Search catalog by query string
   * @param {string} query
   * @returns {UnityApiMetadata[]}
   */
  search(query) {
    const q = query.toLowerCase();
    const results = [];
    for (const entry of this.entries.values()) {
      if (
        entry.id.toLowerCase().includes(q) ||
        entry.unityName.toLowerCase().includes(q) ||
        entry.cocosTarget.target.toLowerCase().includes(q) ||
        (entry.semanticNotes && entry.semanticNotes.toLowerCase().includes(q))
      ) {
        results.push(entry);
      }
    }
    return results;
  }
}

