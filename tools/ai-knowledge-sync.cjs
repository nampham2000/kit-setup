#!/usr/bin/env node
'use strict';

/**
 * AI Knowledge & Skills Deployment Tool
 *
 * Automatically copies and deploys AI instructions, rules, and skills for:
 * - Claude (CLAUDE.md)
 * - OpenAI Codex / ChatGPT Desktop (AGENTS.md, ~/.codex/skills/)
 * - Gemini / Antigravity (GEMINI.md, .gemini/GEMINI.md, ~/.gemini/antigravity/skills/)
 * - GitHub Copilot / Cursor / VS Code (.github/copilot-instructions.md, .cursorrules, .github/skills/)
 *
 * Also generates the high-density ai/PROJECT_MAP.json for instant AI onboarding.
 */

const fs = require('fs');
const path = require('path');
const os = require('os');
const { generateProjectMap } = require('./project-map-generator.cjs');
const { generateTypings } = require('./config-typings-generator.cjs');
const {
  writeManifest,
  renderCommandTable,
  renderCommandList,
  renderLimits,
  renderCoreRules,
} = require('./capability-manifest.cjs');

const PROJECT_ROOT = path.resolve(__dirname, '..', '..');
const SHARED_KIT_AI = path.join(PROJECT_ROOT, 'playable-shared-kit', 'ai');
const HOME_DIR = os.homedir();

/**
 * Khối nội dung được SINH RA từ playable-shared-kit/ai/capabilities.def.cjs.
 * Mọi file hướng dẫn agent chỉ được chứa marker, không chép tay lệnh CLI.
 */
function generatedBlocks() {
  return {
    commands: renderCommandTable(),
    'commands-list': renderCommandList(),
    limits: renderLimits(),
    'core-rules': renderCoreRules(),
  };
}

/**
 * Thay nội dung giữa cặp marker BEGIN/END:GENERATED:<name>.
 * Nếu file chưa có marker, chèn khối mới vào cuối file để không agent nào
 * bị bỏ đói thông tin chỉ vì template quên marker.
 */
function injectGenerated(filePath, blocks) {
  if (!fs.existsSync(filePath)) return { injected: 0, appended: 0 };
  let text = fs.readFileSync(filePath, 'utf8');
  let injected = 0;
  let appended = 0;

  for (const [name, body] of Object.entries(blocks)) {
    const begin = `<!-- BEGIN:GENERATED:${name} -->`;
    const end = `<!-- END:GENERATED:${name} -->`;
    const pattern = new RegExp(
      `${begin.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}[\\s\\S]*?${end.replace(/[.*+?^${}()|[\]\\]/g, '\\$&')}`
    );
    const replacement = `${begin}\n${body}\n${end}`;
    if (pattern.test(text)) {
      text = text.replace(pattern, replacement);
      injected += 1;
    }
  }

  // File nào không có BẤT KỲ marker nào thì bổ sung bảng lệnh vào cuối,
  // để không agent nào bị bỏ đói thông tin. File đã dùng `commands-list`
  // hoặc marker khác thì coi như đã được phục vụ, không chèn thêm.
  if (injected === 0) {
    text = `${text.trimEnd()}\n\n## Hợp đồng lệnh (sinh tự động)\n\n` +
      `<!-- BEGIN:GENERATED:commands -->\n${blocks.commands}\n<!-- END:GENERATED:commands -->\n`;
    appended += 1;
  }

  const stamp = '<!-- Generated by `npm run ai:sync` from playable-shared-kit/ai/capabilities.def.cjs. Do not hand-edit commands. -->';
  if (!text.includes(stamp)) {
    text = `${stamp}\n${text}`;
  }

  fs.writeFileSync(filePath, text, 'utf8');
  return { injected, appended };
}

function copyDirRecursive(src, dest) {
  if (!fs.existsSync(src)) return;
  if (!fs.existsSync(dest)) {
    fs.mkdirSync(dest, { recursive: true });
  }
  const entries = fs.readdirSync(src, { withFileTypes: true });
  for (const entry of entries) {
    const srcPath = path.join(src, entry.name);
    const destPath = path.join(dest, entry.name);
    if (entry.isDirectory()) {
      copyDirRecursive(srcPath, destPath);
    } else {
      fs.copyFileSync(srcPath, destPath);
    }
  }
}

function copyFileSafe(src, dest) {
  if (!fs.existsSync(src)) return false;
  const parentDir = path.dirname(dest);
  if (!fs.existsSync(parentDir)) {
    fs.mkdirSync(parentDir, { recursive: true });
  }
  fs.copyFileSync(src, dest);
  return true;
}

function main() {
  console.log('==> [1/4] Building capability manifest (single source of truth)...');
  let blocks = null;
  try {
    const result = writeManifest();
    blocks = generatedBlocks();
    console.log(`  [ok] ${result.count} capabilities -> ai/CAPABILITIES.json + ai/CORE.md`);
  } catch (err) {
    console.error(`  [FAIL] Could not build capability manifest: ${err.message}`);
    process.exitCode = 1;
    return;
  }

  console.log('==> [2/4] Generating AI Project Map...');
  try {
    generateProjectMap();
    console.log('  [ok] PROJECT_MAP.json generated successfully.');
  } catch (err) {
    console.warn(`  [warn] Could not generate PROJECT_MAP.json: ${err.message}`);
  }

  console.log('==> [3/4] Generating Config TypeScript Typings...');
  try {
    generateTypings();
    console.log('  [ok] PlayableConfigTypes.d.ts generated.');
  } catch (err) {
    console.warn(`  [warn] Could not generate config typings: ${err.message}`);
  }

  console.log('==> [4/4] Deploying AI Provider Knowledge & Skills...');

  const templatesDir = path.join(SHARED_KIT_AI, 'templates');
  const skillsDir = path.join(SHARED_KIT_AI, 'skills');

  // 1. Claude (CLAUDE.md)
  const claudeSrc = path.join(templatesDir, 'CLAUDE.md');
  const claudeDest = path.join(PROJECT_ROOT, 'CLAUDE.md');
  if (copyFileSafe(claudeSrc, claudeDest)) {
    console.log('  [ok] Claude -> CLAUDE.md');
  }

  // 2. Codex / ChatGPT (AGENTS.md + ~/.codex/skills/)
  const agentsSrc = path.join(templatesDir, 'AGENTS.md');
  const agentsDest = path.join(PROJECT_ROOT, 'AGENTS.md');
  copyFileSafe(agentsSrc, agentsDest);

  const codexSkillsDest = path.join(HOME_DIR, '.codex', 'skills');
  copyDirRecursive(skillsDir, codexSkillsDest);
  console.log('  [ok] Codex / ChatGPT -> AGENTS.md, ~/.codex/skills/');

  // 3. Gemini / Antigravity (GEMINI.md, .gemini/GEMINI.md, ~/.gemini/antigravity/skills/)
  const geminiSrc = path.join(templatesDir, 'GEMINI.md');
  copyFileSafe(geminiSrc, path.join(PROJECT_ROOT, 'GEMINI.md'));
  copyFileSafe(geminiSrc, path.join(PROJECT_ROOT, '.gemini', 'GEMINI.md'));

  const antigravitySkillsDest = path.join(HOME_DIR, '.gemini', 'antigravity', 'skills');
  copyDirRecursive(skillsDir, antigravitySkillsDest);

  const workspaceAgentsSkills = path.join(PROJECT_ROOT, '.agents', 'skills');
  copyDirRecursive(skillsDir, workspaceAgentsSkills);
  console.log('  [ok] Gemini / Antigravity -> GEMINI.md, ~/.gemini/antigravity/skills/, .agents/skills/');

  // 4. GitHub Copilot / Cursor (.github/copilot-instructions.md, .cursorrules, .github/skills/)
  const copilotSrcCandidates = [
    path.join(templatesDir, '.github', 'copilot-instructions.md'),
    path.join(templatesDir, 'copilot-instructions.md'),
    path.join(PROJECT_ROOT, 'playable-shared-kit', '.github', 'copilot-instructions.md')
  ];
  for (const src of copilotSrcCandidates) {
    if (fs.existsSync(src)) {
      copyFileSafe(src, path.join(PROJECT_ROOT, '.github', 'copilot-instructions.md'));
      break;
    }
  }

  const cursorSrc = path.join(templatesDir, '.cursorrules');
  copyFileSafe(cursorSrc, path.join(PROJECT_ROOT, '.cursorrules'));

  const projectSkillsDest = path.join(PROJECT_ROOT, '.github', 'skills');
  copyDirRecursive(skillsDir, projectSkillsDest);
  console.log('  [ok] Copilot / Cursor / VSCode -> .github/copilot-instructions.md, .cursorrules, .github/skills/');

  // 5. Render lệnh từ manifest vào MỌI file hướng dẫn agent đã deploy.
  //    Đây là bước biến "chép tay ở 13 nơi" thành "sinh từ 1 nguồn".
  const renderTargets = [
    path.join(PROJECT_ROOT, 'CLAUDE.md'),
    path.join(PROJECT_ROOT, 'AGENTS.md'),
    path.join(PROJECT_ROOT, 'GEMINI.md'),
    path.join(PROJECT_ROOT, '.gemini', 'GEMINI.md'),
    path.join(PROJECT_ROOT, '.cursorrules'),
    path.join(PROJECT_ROOT, '.github', 'copilot-instructions.md'),
  ];
  for (const skillRoot of [projectSkillsDest, workspaceAgentsSkills, codexSkillsDest, antigravitySkillsDest]) {
    const skillFile = path.join(skillRoot, 'unity-to-cocos-porting', 'SKILL.md');
    if (fs.existsSync(skillFile)) renderTargets.push(skillFile);
  }

  let renderedFiles = 0;
  let renderedBlocks = 0;
  let appendedBlocks = 0;
  for (const target of renderTargets) {
    if (!fs.existsSync(target)) continue;
    const stats = injectGenerated(target, blocks);
    renderedFiles += 1;
    renderedBlocks += stats.injected;
    appendedBlocks += stats.appended;
  }
  console.log(`  [ok] Rendered command contract into ${renderedFiles} file(s): ${renderedBlocks} block(s) replaced, ${appendedBlocks} appended.`);

  console.log('  [ok] All AI knowledge bases, rules, and maps deployed successfully.');
  console.log('  [next] Chạy `npm run ai:contract:verify` để chứng minh mọi lệnh khớp CLI thật.\n');
}

main();
